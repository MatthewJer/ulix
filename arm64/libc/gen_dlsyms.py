#!/usr/bin/env python3
"""Writes dlsyms.c, the table of symbols for dlsym (see dlshim.c).

usage: gen_dlsyms.py READELF EXECUTABLE > dlsyms.c        (READELF: the readelf of the cross toolchain; EXECUTABLE: the program, not stripped)
       gen_dlsyms.py --extern NM libc.a > dlundef.ld      (see below)
       gen_dlsyms.py - > dlsyms.c                    (an empty table, for the first link)

The names are those of the global functions and variables of the finished program, sorted the way strcmp () sorts them. The internal
names of musl (two leading underscores) and the symbols that the linker makes up (_end, __bss_start, ...) are left out.
"""
import subprocess, sys

if sys.argv[1] == '--extern':          # gen_dlsyms.py --extern NM libc.a: a linker script that makes the linker take every public function of the C library
    out = subprocess.run([sys.argv[2], '-g', '--defined-only', sys.argv[3]], capture_output=True, text=True, check=True).stdout
    fn = sorted({f[2] for f in map(str.split, out.splitlines()) if len(f) == 3 and f[1] in 'TW' and not f[2].startswith(('_', 'dl'))})
    print('/* generated by gen_dlsyms.py --extern: every public function of libc.a, so that ctypes finds it with dlsym */')
    print('EXTERN(' + ' '.join(fn) + ')')
    sys.exit(0)

names = set()
if sys.argv[1] != '-':
    out = subprocess.run([sys.argv[1], '-sW', sys.argv[2]], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():                       # Num: Value Size Type Bind Vis Ndx Name   (thread-local variables have type TLS: left out)
        f = line.split()
        if len(f) == 8 and f[3] in ('FUNC', 'OBJECT') and f[4] in ('GLOBAL', 'WEAK') and f[6] != 'UND' and not f[7].startswith('__') \
           and f[7] not in ('_start', '_end', '_edata', '_etext', 'dl_table', 'dl_count') and '@' not in f[7]:
            names.add(f[7])
names = sorted(names, key=lambda s: s.encode())
print('/* generated by gen_dlsyms.py: the symbols of the program, sorted by name (dlshim.c) */')
for n in names: print('extern char %s[];' % n)
print('struct dl_entry { const char *name; void *addr; };')
print('const struct dl_entry dl_table[] = {')
for n in names: print('  { "%s", %s },' % (n, n))
print('  { 0, 0 } };' if names else '  { 0, 0 } };')
print('const unsigned dl_count = %d;' % len(names))
