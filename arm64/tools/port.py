#!/usr/bin/env python3
"""Pick functions and global variables out of the tangled Ulix kernel for the ARM64 build.

usage: port.py GENDIR MANIFEST OUTFILE

GENDIR holds ulix-decl.h, ulix-globals.c and ulix-functions.c (tangled from ulix-book.nw by
the Makefile).  MANIFEST lists one name per line ("function NAME" or "global NAME"; "#" starts
a comment; a trailing "*" in a name matches a prefix).  OUTFILE gets the declarations plus the
selected pieces, in the order they appear in the book.
"""
import re, sys

gendir, manifest, outfile = sys.argv[1:4]

def read_manifest(path):
    funcs, globs = [], []
    for line in open(path):
        line = line.split('#')[0].strip()
        if not line: continue
        kind, name = line.split()
        (funcs if kind == 'function' else globs).append(name)
    return funcs, globs

def match(name, patterns):
    for p in patterns:
        if p.endswith('*') and name.startswith(p[:-1]): return True
        if name == p: return True
    return False

def strip(line):
    """remove string/char literals and comments, so that only structural braces are left"""
    line = re.sub(r'"(\\.|[^"\\])*"|\'(\\.|[^\'\\])*\'', '', line)
    line = re.sub(r'/\*.*?\*/', '', line)
    return line.split('//')[0]

def split_functions(lines):
    """yield (name, text) for every top-level function definition"""
    i, n = 0, len(lines)
    head = re.compile(r'^[A-Za-z_][\w\s\*]*?\b(\w+)\s*\([^;{]*$'                    # prototype continues on the next line
                      r'|^[A-Za-z_][\w\s\*]*?\b(\w+)\s*\([^;{]*\)\s*(\{.*)?$')       # name (args) [{ ... }]
    while i < n:
        l = lines[i]
        if l and not l[0].isspace() and not l.startswith(('#', '//', '/*', '}', 'typedef', 'extern', 'struct ', 'enum ')) \
           or (l.startswith('struct ') and '(' in l and not l.rstrip().endswith(';')):
            m = head.match(l)
            if m and (not l.rstrip().endswith(';') or '{' in l):   # a bare 'f (...);' is a prototype
                name = m.group(1) or m.group(2)
                j = i
                while j < n and '{' not in lines[j] and j < i + 4: j += 1
                if j < n and '{' in lines[j]:
                    depth, k = 0, j
                    while k < n:                       # brace counting, comments and strings stripped
                        code = strip(lines[k])
                        depth += code.count('{') - code.count('}')
                        if depth <= 0: break
                        k += 1
                    yield name, '\n'.join(lines[i:k + 1])
                    i = k
        i += 1

def split_globals(lines):
    """yield (name, text) for every top-level variable definition"""
    i, n = 0, len(lines)
    while i < n:
        l = lines[i]
        if l and not l[0].isspace() and not l.startswith(('#', '//', '/*', '}', 'typedef', 'extern')):
            j, depth = i, 0
            while j < n:
                code = strip(lines[j])
                depth += code.count('{') - code.count('}')
                if depth <= 0 and code.rstrip().endswith(';'): break
                j += 1
            text = '\n'.join(lines[i:j + 1])
            head = text.split('=')[0].split('//')[0]
            m = re.findall(r'(\w+)\s*(?:\[[^\]]*\]\s*)*(?:__attribute__.*)?;?\s*$', head.strip())
            if m: yield m[-1], text
            i = j
        i += 1

funcs, globs = read_manifest(manifest)
flines = open(gendir + '/ulix-functions.c').read().split('\n')
glines = open(gendir + '/ulix-globals.c').read().split('\n')

out = ['// GENERATED by tools/port.py from ../ulix-book.nw -- do not edit', '#include "ulix-decl.h"', '']
found_g = set()
externs = ['// GENERATED by tools/port.py -- extern declarations of the selected global variables',
           '#include "ulix-decl.h"', '']
def extern_of(text):
    """declaration without initializer and attributes, as an extern declaration"""
    t = re.sub(r'//.*', '', text)
    t = re.sub(r'__attribute__\s*\(\(.*?\)\)', '', t)
    depth, cut = 0, None
    for i, ch in enumerate(t):                       # cut at the first '=' outside brackets
        if ch in '[(': depth += 1
        elif ch in '])': depth -= 1
        elif ch == '=' and depth == 0: cut = i; break
    if cut is not None: t = t[:cut]
    return 'extern ' + t.strip().rstrip(';').strip() + ';'
for name, text in split_globals(glines):
    if match(name, globs):
        out += ['// global: ' + name, text, ''];  found_g.add(name)
        externs.append(extern_of(text))
found_f = set()
for name, text in split_functions(flines):
    if match(name, funcs):
        out += ['// function: ' + name, text, ''];  found_f.add(name)
open(outfile, 'w').write('\n'.join(out) + '\n')
open(gendir + '/ulix-api.h', 'w').write('\n'.join(externs) + '\n')

missing = [f for f in funcs if not f.endswith('*') and f not in found_f] + \
          [g for g in globs if not g.endswith('*') and g not in found_g]
print('port.py: %d functions, %d globals written to %s' % (len(found_f), len(found_g), outfile))
if missing: print('port.py: NOT FOUND in the book: ' + ' '.join(missing)); sys.exit(1)
