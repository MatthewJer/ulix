#!/usr/bin/env python3
"""Writes a C header with size and byte sum of some files of a Minix image, computed by the independent
parser in minix_check.py.  The kernel tests compare what the kernel reads with these values.

usage: disk_expected.py IMAGE PATH [PATH ...] > gen/disk_expected.h
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from minix_check import Minix

fs = Minix(sys.argv[1])
print('// GENERATED by tools/disk_expected.py from %s -- do not edit' % sys.argv[1])
for path in sys.argv[2:]:
    n = fs.lookup(path)
    if n is None: sys.exit('not found: ' + path)
    data = fs.read(n)
    name = re.sub(r'[^A-Za-z0-9]', '_', path.strip('/')).upper()
    print('#define EXPECT_%s_SIZE %d' % (name, len(data)))
    print('#define EXPECT_%s_SUM  %du' % (name, sum(data) & 0xffffffff))
