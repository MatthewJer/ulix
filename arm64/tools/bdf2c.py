#!/usr/bin/env python3
# Turns the BDF bitmap fonts of third_party/terminus into a C table for the HDMI console (arm64/gen/font.c; chapter "Screen and keyboard").
# Usage: bdf2c.py ter-u16n.bdf ter-u24n.bdf ter-u32n.bdf > font.c       (smallest font first)
# Only the characters the console can show are taken: ASCII, Latin-1, arrows, box drawing and block elements, the bullet, the euro sign and U+FFFD.
import sys, os

WANTED = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + [0x2022, 0x20ac, 0xfffd] + list(range(0x2190, 0x2194)) + list(range(0x2500, 0x25a0))

def read_bdf(path):
    glyphs, w, h = {}, 0, 0
    cp, rows, inbits = None, [], False
    for line in open(path):
        t = line.split()
        if not t: continue
        if t[0] == 'FONTBOUNDINGBOX': w, h = int(t[1]), int(t[2])
        elif t[0] == 'ENCODING': cp = int(t[1])
        elif t[0] == 'BITMAP': rows, inbits = [], True
        elif t[0] == 'ENDCHAR':
            inbits = False
            if cp in WANTED: glyphs[cp] = rows
        elif inbits: rows.append(bytes.fromhex(t[0]))
    return w, h, glyphs

out = ['/* generated by tools/bdf2c.py from third_party/terminus (SIL OFL 1.1, Copyright (C) 2020 Dimitar Toshkov Zhekov); do not edit */',
       '#include "fb.h"', '']
names = []
for path in sys.argv[1:]:
    w, h, glyphs = read_bdf(path)
    bpr = (w + 7) // 8
    cps = sorted(glyphs)
    n = 'font%dx%d' % (w, h)
    names.append((n, w, h))
    out.append('static const unsigned short %s_cp[] = {' % n)
    out.append(',\n'.join(', '.join('0x%04x' % c for c in cps[i:i+8]) for i in range(0, len(cps), 8)))
    out.append('};')
    out.append('static const unsigned char %s_bits[] = {' % n)
    for c in cps:
        r = glyphs[c]
        assert len(r) == h and all(len(x) == bpr for x in r), (path, hex(c))
        out.append('  ' + ', '.join('0x%02x' % b for x in r for b in x) + ',')
    out.append('};')
    out.append('')
out.append('const struct font fb_fonts[] = {')
for n, w, h in names:
    out.append('  { %d, %d, %d, sizeof %s_cp / sizeof %s_cp[0], %s_cp, %s_bits },' % (w, h, (w + 7) // 8, n, n, n, n))
out.append('};')
out.append('const int fb_nfonts = %d;' % len(names))
print('\n'.join(out))
